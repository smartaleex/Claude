#define CHAR_W 6
#define CHAR_H 8

void txt_draw_char(int x, int y, char c, u16 fg, u16 bg) {
    if (c < 32 || c > 126) c = ' ';
    const u8* bmap = font6x8[c - 32];
    /* Resolve palette indices once per character, not once per pixel */
    u8 fg_idx = gfx_color_idx(fg);
    u8 bg_idx = (bg != 0xFFFF) ? gfx_color_idx(bg) : 0xFF;
    for (int row = 0; row < CHAR_H; row++) {
        u8 bits = bmap[row];
        for (int col = 0; col < CHAR_W; col++) {
            /* bit0 = leftmost pixel (LSB-first font encoding) */
            u8 idx = (bits & (1 << col)) ? fg_idx : bg_idx;
            if (idx != 0xFF)
                gfx_draw_pixel_idx(x + col, y + row, idx);
        }
    }
}

void txt_draw_str(int x, int y, const char* s, u16 fg, u16 bg) {
    int cx = x;
    while (*s) {
        if (*s == '\n') { y += CHAR_H + 1; cx = x; s++; continue; }
        txt_draw_char(cx, y, *s++, fg, bg);
        cx += CHAR_W + 1;
    }
}

void txt_draw_int(int x, int y, int n, u16 fg, u16 bg) {
    char buf[12];
    int neg = 0, i = 10;
    buf[11] = '\0';
    if (n < 0) { neg = 1; n = -n; }
    if (n == 0) { buf[i--] = '0'; }
    while (n > 0) {
        buf[i--] = '0' + gba_mod(n, 10);
        n = gba_div(n, 10);
    }
    if (neg) buf[i--] = '-';
    txt_draw_str(x, y, buf + i + 1, fg, bg);
}

void txt_draw_str_centered(int y, const char* s, u16 fg, u16 bg) {
    int len = 0;
    const char* p = s;
    while (*p++) len++;
    int x = (SCREEN_W - len * (CHAR_W + 1)) / 2;
    txt_draw_str(x, y, s, fg, bg);
}
